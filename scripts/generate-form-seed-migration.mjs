import fs from "node:fs";

const formSeed = JSON.parse(fs.readFileSync("seeds/primer-evento-inauguracion-otca.json", "utf8"));
const catalogSeed = JSON.parse(fs.readFileSync("seeds/catalogos-formulario-asistencia.json", "utf8"));

const outputPath = "migrations/0005_seed_formulario_catalogos_otca.sql";

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function idFrom(...parts) {
  return parts
    .join("_")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 180);
}

const lines = [
  "-- Migration: formulario y catalogos iniciales OTCA",
  "-- Generated by scripts/generate-form-seed-migration.mjs",
  "",
  "PRAGMA foreign_keys = ON;",
  ""
];

const form = formSeed.form;
const formId = "form_inauguracion_otca";
lines.push(
  `INSERT INTO forms (id, event_id, name, status, short_link_slug, welcome_title_template, cloned_from_form_id) VALUES (${sql(formId)}, 'evt_inauguracion_otca', ${sql(form.name)}, 'active', ${sql(form.short_link_slug)}, ${sql(form.welcome_title_template)}, NULL)`,
  "ON CONFLICT(id) DO UPDATE SET",
  "  name = excluded.name,",
  "  status = excluded.status,",
  "  short_link_slug = excluded.short_link_slug,",
  "  welcome_title_template = excluded.welcome_title_template,",
  "  updated_at = CURRENT_TIMESTAMP;",
  ""
);

for (const section of form.sections) {
  const sectionId = `sec_${section.key}`;
  lines.push(
    `INSERT INTO form_sections (id, form_id, section_key, title, order_index) VALUES (${sql(sectionId)}, ${sql(formId)}, ${sql(section.key)}, ${sql(section.title)}, ${section.order})`,
    "ON CONFLICT(form_id, section_key) DO UPDATE SET",
    "  title = excluded.title,",
    "  order_index = excluded.order_index,",
    "  updated_at = CURRENT_TIMESTAMP;",
    ""
  );

  for (const field of section.fields) {
    const fieldId = `fld_${field.key}`;
    const config = field.type === "radio" ? JSON.stringify({ options: ["SI", "NO"] }) : "{}";
    lines.push(
      `INSERT INTO form_fields (id, form_id, section_id, field_key, label, field_type, catalog_key, is_required, order_index, config) VALUES (${sql(fieldId)}, ${sql(formId)}, ${sql(sectionId)}, ${sql(field.key)}, ${sql(field.label)}, ${sql(field.type)}, ${sql(field.catalog_key)}, ${field.required ? 1 : 0}, ${field.order}, ${sql(config)})`,
      "ON CONFLICT(form_id, field_key) DO UPDATE SET",
      "  section_id = excluded.section_id,",
      "  label = excluded.label,",
      "  field_type = excluded.field_type,",
      "  catalog_key = excluded.catalog_key,",
      "  is_required = excluded.is_required,",
      "  order_index = excluded.order_index,",
      "  config = excluded.config,",
      "  updated_at = CURRENT_TIMESTAMP;",
      ""
    );
  }
}

for (const [catalogKey, catalog] of Object.entries(catalogSeed.catalogs)) {
  const catalogId = `cat_${catalogKey}`;
  lines.push(
    `INSERT INTO system_catalogs (id, catalog_key, name, description, status) VALUES (${sql(catalogId)}, ${sql(catalogKey)}, ${sql(catalogKey)}, ${sql(`Catalogo ${catalogKey} importado desde ${catalog.source_sheet}`)}, 'active')`,
    "ON CONFLICT(catalog_key) DO UPDATE SET",
    "  name = excluded.name,",
    "  description = excluded.description,",
    "  status = excluded.status,",
    "  updated_at = CURRENT_TIMESTAMP;",
    ""
  );

  for (const entry of catalog.entries) {
    const itemId = `catitem_${idFrom(catalogKey, entry.id, entry.nombre)}`;
    const parentId = entry.parent_id ? `catitem_${idFrom(entry.parent_catalog_key ?? "", entry.parent_id, "")}` : null;
    const metadata = JSON.stringify({ source: entry.source ?? null });
    lines.push(
      `INSERT OR IGNORE INTO system_catalog_items (id, catalog_id, parent_item_id, source_id, name, description, status, metadata) VALUES (${sql(itemId)}, ${sql(catalogId)}, ${sql(parentId)}, ${sql(entry.id)}, ${sql(entry.nombre)}, ${sql(entry.descripcion)}, ${sql(entry.estado ?? "active")}, ${sql(metadata)});`
    );
  }

  lines.push("");
}

fs.writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`Generated ${outputPath}`);
